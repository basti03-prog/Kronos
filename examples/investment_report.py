"""
investment_report.py

Description:
    Generates a one-page AI investment report for any Yahoo Finance ticker:
    a Kronos price forecast with Monte-Carlo confidence bands, trend analysis,
    support/resistance levels, historical + forecast volatility, technical
    indicators (RSI, MACD, EMA50/EMA200), and a transparent bullish/bearish
    composite probability. Saved as both PDF and PNG.

    Kronos forecasts a single path per call; to get a distribution (needed for
    confidence intervals and the ensemble bullish/bearish probability) this
    script runs the model --ensemble_size times independently (each a fresh
    stochastic sample) and aggregates the resulting close-price paths.

Usage:
    python investment_report.py --ticker AAPL
    python investment_report.py --ticker SAP.DE --pred_len 60 --ensemble_size 12

Output:
    - ./outputs/report_<TICKER>.pdf
    - ./outputs/report_<TICKER>.png

DISCLAIMER: This report is generated by a machine-learning model for research
and educational purposes only. It is not financial advice.
"""

